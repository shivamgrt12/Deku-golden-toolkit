"""Split instruction.md into requirement units, so every one can be accounted for.

The checklist is genkit's breakdown of the brief. If it missed a requirement, no
grader checks it and nothing downstream notices. This module numbers the brief's
own requirement units so P0 can map each one -- to the checklist item(s) that
capture it, or to a golden test of ours when the checklist does not:

  every bullet and numbered item
  every table data row
  every sentence elsewhere that states an obligation (must, never, only, ...)

Units are numbered in document order (B-001, B-002, ...). The brief is never
edited during a golden run, so the numbering is stable for the whole run.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

OBLIGATION = re.compile(
    r"\b(must|never|only|every|exactly|always|cannot|can't|should|required|requires|at least|"
    r"at most|refused?|rejects?|rejected|denied|denies|no more than|not before|before any)\b", re.I)
BULLET = re.compile(r"^\s*(?:[-*+]|\d{1,2}[.)])\s+(.*\S)")
TABLE_ROW = re.compile(r"^\s*\|(.+)\|\s*$")
SENTENCE_END = re.compile(r"(?<=[.!?])\s+(?=[A-Z`\"(])")


@dataclass
class Unit:
    id: str
    section: str
    kind: str          # bullet | row | sentence
    text: str
    line: int


def _clean(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def units(b) -> list[Unit]:
    path = Path(b.root) / "instruction.md"
    if not path.is_file():
        return []
    out: list[Unit] = []
    section, header_seen, para, para_line = "", False, [], 0

    def flush_para():
        nonlocal para
        if para:
            text = _clean(" ".join(para))
            for sentence in SENTENCE_END.split(text):
                if len(sentence) > 12:
                    out.append(Unit("", section, "sentence", sentence, para_line))
        para = []

    in_code, in_bullet = False, False
    for n, raw in enumerate(path.read_text().splitlines(), 1):
        line = raw.rstrip()
        if line.strip().startswith("```"):
            flush_para()
            in_code = not in_code
            continue
        if in_code:
            continue
        h = re.match(r"^(#{1,4})\s+(.+)$", line)
        if h:
            flush_para()
            in_bullet = False
            if len(h.group(1)) <= 3:
                section = _clean(h.group(2))
            header_seen = False
            continue
        row = TABLE_ROW.match(line)
        if row:
            flush_para()
            in_bullet = False
            cells = [c.strip() for c in row.group(1).split("|")]
            if all(set(c) <= set("-: ") for c in cells):
                continue
            if not header_seen:          # the header row names columns, it requires nothing
                header_seen = True
                continue
            text = _clean(" | ".join(c for c in cells if c))
            if text:
                out.append(Unit("", section, "row", text, n))
            continue
        header_seen = False
        bullet = BULLET.match(line)
        if bullet:
            flush_para()
            out.append(Unit("", section, "bullet", _clean(bullet.group(1)), n))
            in_bullet = True
            continue
        if not line.strip():
            flush_para()
            in_bullet = False
            continue
        if in_bullet and not para:
            # A bullet's wrapped line continues it, indented or not (markdown's lazy
            # continuation) -- until a blank line ends the list item.
            out[-1].text = _clean(out[-1].text + " " + line)
            continue
        if not para:
            para_line = n
        para.append(line.strip())
    flush_para()
    for i, u in enumerate(out, 1):
        u.id = f"B-{i:03d}"
    return out


def render(b, found: list[Unit]) -> str:
    lines = [f"# Brief units — {b.name}", "",
             "Every requirement unit of instruction.md, numbered in document order. Map each one in",
             "PLAN.md ## Brief coverage. Generated by golden/bin/golden-brief; never edit it.", "",
             "| Unit | Section | Line | Text |", "|---|---|---|---|"]
    for u in found:
        lines.append(f"| {u.id} | {u.section} | {u.line} | {u.text.replace('|', '/')} |")
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------ suggestions
STOP = set("""a an the and or of to in on at for with by from as is are be been being it its this that these
those there their they them then than so such not no nor but if into onto over under same each every only
must never should can may will would one two any all also when where which while who whom whose what how
own more most less very just""".split())
ITEM = re.compile(r"^- \[[ xX]\] `(C-[A-Z]{2}-\d+)` `[a-z]+` (.+?)\s*`src:\s*(.+?)`\s*$", re.M)


def words(text: str) -> set[str]:
    return {w for w in re.findall(r"[a-z0-9][a-z0-9_-]{2,}", text.lower()) if w not in STOP}


def checklist(b) -> dict[str, tuple[str, str]]:
    """id -> (text, src) for every checklist item."""
    path = Path(b.root) / "solution" / "checklist.md"
    return {m[0]: (m[1], m[2]) for m in ITEM.findall(path.read_text())} if path.is_file() else {}


def suggest(unit: Unit, items: dict[str, tuple[str, str]], k: int = 3) -> list[str]:
    """The checklist items most likely to capture a unit: shared wording, same section first."""
    uw, scored = words(unit.text), []
    for iid, (text, src) in items.items():
        shared = len(uw & words(text))
        if shared < 2:
            continue
        same = unit.section and unit.section.lower().split()[0] in src.lower()
        scored.append((shared + (2 if same else 0), iid))
    return [iid for _, iid in sorted(scored, reverse=True)[:k]]


def write(b) -> Path:
    """_handoff/golden/brief-units.md: every unit, with suggested checklist items."""
    found, items = units(b), checklist(b)
    lines = [f"# Brief units — {b.name}", "",
             f"{len(found)} requirement units of instruction.md, numbered in document order. Map every one",
             "in PLAN.md `## Brief coverage`: to checklist ids, to `not in checklist: <golden test>`, or to",
             "`context: <why>` when it states no obligation. Suggestions are hints, never a mapping.",
             "Generated by golden; never edit it.", "",
             "| Unit | Section | Line | Text | Suggested |", "|---|---|---|---|---|"]
    for u in found:
        lines.append(f"| {u.id} | {u.section} | {u.line} | {u.text.replace('|', '/')} | "
                     f"{', '.join(suggest(u, items))} |")
    path = b.golden_dir / "brief-units.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return path
